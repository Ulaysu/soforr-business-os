using System.Diagnostics.CodeAnalysis;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using Soforr.Application.Organizations;
using Soforr.Infrastructure.Persistence;

namespace Soforr.Api.IntegrationTests.Postgres;

/// <summary>
/// A class fixture that gives one test class its own, empty PostgreSQL database with the application's migrations
/// applied (ADR 0005). Because every class has a private database, classes can run in parallel, in any order,
/// without sharing data. Using the fixture also proves that the migrations apply to an empty database.
/// Use it with <c>IClassFixture&lt;PostgresDatabaseFixture&gt;</c> and tag the class
/// <c>[Trait("Category", "Integration")]</c>.
/// </summary>
public sealed class PostgresDatabaseFixture : IAsyncLifetime
{
    private string _administrationConnectionString = string.Empty;

    /// <summary>The generated name of this class's database.</summary>
    public string DatabaseName { get; } = "test_" + Guid.NewGuid().ToString("N");

    /// <summary>A connection string to this class's database.</summary>
    public string ConnectionString { get; private set; } = string.Empty;

    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "The database name is generated by this fixture (hex digits only), never supplied by input.")]
    public async Task InitializeAsync()
    {
        _administrationConnectionString = await SharedPostgresContainer.GetAdministrationConnectionStringAsync();

        await using (var admin = new NpgsqlConnection(_administrationConnectionString))
        {
            await admin.OpenAsync();
            await using var create = admin.CreateCommand();
            create.CommandText = $"CREATE DATABASE \"{DatabaseName}\"";
            await create.ExecuteNonQueryAsync();
        }

        ConnectionString = new NpgsqlConnectionStringBuilder(_administrationConnectionString) { Database = DatabaseName }.ConnectionString;

        await using var context = CreateContext();
        await EnsureEmptyAsync(context);
        await context.Database.MigrateAsync();
    }

    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "The database name is generated by this fixture (hex digits only), never supplied by input.")]
    public async Task DisposeAsync()
    {
        NpgsqlConnection.ClearAllPools();

        await using var admin = new NpgsqlConnection(_administrationConnectionString);
        await admin.OpenAsync();
        await using var drop = admin.CreateCommand();
        drop.CommandText = $"DROP DATABASE IF EXISTS \"{DatabaseName}\" WITH (FORCE)";
        await drop.ExecuteNonQueryAsync();
    }

    /// <summary>
    /// A new context on this class's database, acting for <paramref name="organizationId"/>. Without one the context has
    /// no organization, so the tenant query filters match nothing: read test data with <c>IgnoreQueryFilters()</c>.
    /// The caller disposes it.
    /// </summary>
    public AppDbContext CreateContext(Guid? organizationId = null) =>
        new(new DbContextOptionsBuilder<AppDbContext>().UseNpgsql(ConnectionString).Options, new FixedOrganizationContext(organizationId));

    private sealed class FixedOrganizationContext(Guid? organizationId) : IOrganizationContext
    {
        public Guid? OrganizationId { get; } = organizationId;
    }

    private static async Task EnsureEmptyAsync(AppDbContext context)
    {
        var connection = context.Database.GetDbConnection();
        await connection.OpenAsync();
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public'";
        var tables = Convert.ToInt32(await command.ExecuteScalarAsync(), System.Globalization.CultureInfo.InvariantCulture);
        await connection.CloseAsync();

        if (tables != 0)
        {
            throw new InvalidOperationException($"The new test database was expected to be empty but has {tables} table(s).");
        }
    }
}
